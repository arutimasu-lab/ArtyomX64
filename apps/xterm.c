static long sc0(long n)
{
    long r;
    __asm__ volatile("int $0x81" : "=a"(r) : "a"(n) : "memory");
    return r;
}

static long sc1(long n, long a)
{
    long r;
    __asm__ volatile("int $0x81" : "=a"(r) : "a"(n), "D"(a) : "memory");
    return r;
}

static long sc3(long n, long a, long b, long c)
{
    long r;
    __asm__ volatile("int $0x81" : "=a"(r) : "a"(n), "D"(a), "S"(b), "d"(c) : "memory");
    return r;
}

static int sys_read(int fd, void *buf, int len) { return (int)sc3(SYS_read, fd, (long)buf, len); }
static int sys_write(int fd, const void *buf, int len) { return (int)sc3(SYS_write, fd, (long)buf, len); }
static int sys_open(const char *path, int flags, int mode) { return (int)sc3(SYS_open, (long)path, flags, mode); }
static int sys_close(int fd) { return (int)sc1(SYS_close, fd); }
static int sys_socket(int d, int t, int p) { return (int)sc3(SYS_socket, d, t, p); }
static int sys_connect(int fd, const void *a, int l) { return (int)sc3(SYS_connect, fd, (long)a, l); }
static void sys_exit(int c) { sc1(SYS_exit, c); __builtin_unreachable(); }

static void xt_clear(void)
{
    for (int y = 0; y < XT_ROWS; y++) {
        for (int x = 0; x < XT_COLS; x++)
            screen[y][x] = ' ';
        screen[y][XT_COLS] = 0;
    }
    cursor_x = 0;
    cursor_y = 0;
}

static void xt_scroll(void)
{
    for (int y = 0; y < XT_ROWS - 1; y++) {
        for (int x = 0; x <= XT_COLS; x++)
            screen[y][x] = screen[y + 1][x];
    }
    for (int x = 0; x < XT_COLS; x++)
        screen[XT_ROWS - 1][x] = ' ';
    screen[XT_ROWS - 1][XT_COLS] = 0;
}

static void xt_putc(char c)
{
    if (c == '\r') { cursor_x = 0; return; }
    if (c == '\n') {
        cursor_x = 0;
        cursor_y++;
        if (cursor_y >= XT_ROWS) { xt_scroll(); cursor_y = XT_ROWS - 1; }
        return;
    }
    if (c == '\b') {
        if (cursor_x > 0) cursor_x--;
        screen[cursor_y][cursor_x] = ' ';
        return;
    }
    if (c == '\t') {
        cursor_x = (cursor_x + 8) & ~7;
        if (cursor_x >= XT_COLS) cursor_x = XT_COLS - 1;
        return;
    }
    if (c < 32 && c != 27) return;
    if (c == 27) return;
    screen[cursor_y][cursor_x] = c;
    cursor_x++;
    if (cursor_x >= XT_COLS) {
        cursor_x = 0;
        cursor_y++;
        if (cursor_y >= XT_ROWS) { xt_scroll(); cursor_y = XT_ROWS - 1; }
    }
}

static void xt_puts(const char *s) { while (*s) xt_putc(*s++); }

static void x11_put16(uint8_t *p, uint16_t v) { p[0] = (uint8_t)v; p[1] = (uint8_t)(v >> 8); }
static void x11_put32(uint8_t *p, uint32_t v) { p[0] = (uint8_t)v; p[1] = (uint8_t)(v >> 8); p[2] = (uint8_t)(v >> 16); p[3] = (uint8_t)(v >> 24); }

static void x11_send(const void *buf, int len)
{
    int off = 0;
    while (off < len) {
        int w = sys_write(x11_fd, (const uint8_t*)buf + off, len - off);
        if (w <= 0) break;
        off += w;
    }
}

static void x11_create_window(uint32_t wid, int x, int y, int w, int h)
{
    uint8_t p[32];
    for (int i = 0; i < 32; i++) p[i] = 0;
    p[0] = 1;
    p[1] = 24;
    x11_put16(p + 2, 8);
    x11_put32(p + 4, wid);
    x11_put32(p + 8, 0x101);
    x11_put16(p + 12, (uint16_t)x);
    x11_put16(p + 14, (uint16_t)y);
    x11_put16(p + 16, (uint16_t)w);
    x11_put16(p + 18, (uint16_t)h);
    x11_put16(p + 20, 0);
    x11_put16(p + 22, 1);
    x11_put32(p + 24, 0);
    x11_put32(p + 28, 0);
    x11_send(p, 32);
    x11_seq++;
}

static void x11_map_window(uint32_t wid)
{
    uint8_t p[8];
    p[0] = 8; p[1] = 0;
    x11_put16(p + 2, 2);
    x11_put32(p + 4, wid);
    x11_send(p, 8);
    x11_seq++;
}

static void x11_create_gc(uint32_t gid, uint32_t drawable)
{
    uint8_t p[24];
    for (int i = 0; i < 24; i++) p[i] = 0;
    p[0] = 55; p[1] = 0;
    x11_put16(p + 2, 6);
    x11_put32(p + 4, gid);
    x11_put32(p + 8, drawable);
    x11_put32(p + 12, 0x00000003);
    x11_put32(p + 16, 0xFFFFFF);
    x11_put32(p + 20, 0x000000);
    x11_send(p, 24);
    x11_seq++;
}

static void x11_poly_fill_rect(uint32_t drawable, uint32_t gc, int x, int y, int w, int h)
{
    uint8_t p[20];
    p[0] = 70; p[1] = 0;
    x11_put16(p + 2, 5);
    x11_put32(p + 4, drawable);
    x11_put32(p + 8, gc);
    x11_put16(p + 12, (uint16_t)x);
    x11_put16(p + 14, (uint16_t)y);
    x11_put16(p + 16, (uint16_t)w);
    x11_put16(p + 18, (uint16_t)h);
    x11_send(p, 20);
    x11_seq++;
}

static void x11_put_image(uint32_t drawable, int x, int y, int w, int h, const uint8_t *img)
{
    int img_len = w * h * 4;
    int total = 24 + img_len;
    int padded = (total + 3) & ~3;
    uint8_t hdr[24];
    hdr[0] = 72; hdr[1] = 2;
    x11_put16(hdr + 2, (uint16_t)(padded / 4));
    x11_put32(hdr + 4, drawable);
    x11_put32(hdr + 8, 0);
    x11_put16(hdr + 12, (uint16_t)w);
    x11_put16(hdr + 14, (uint16_t)h);
    x11_put16(hdr + 16, (uint16_t)x);
    x11_put16(hdr + 18, (uint16_t)y);
    hdr[20] = 0; hdr[21] = 0; hdr[22] = 24; hdr[23] = 0;
    x11_send(hdr, 24);
    x11_send(img, img_len);
    if (padded > total) { uint8_t z[4] = {0,0,0,0}; x11_send(z, padded - total); }
    x11_seq++;
}

static void xt_render(void)
{
    if (!dirty) return;
    dirty = false;
    static uint8_t cell_img[XT_W * 8 * 4];
    for (int y = 0; y < XT_ROWS; y++) {
        for (int x = 0; x < XT_COLS; x++) {
            char c = screen[y][x];
            uint32_t bg = XT_BG;
            uint32_t fg = XT_FG;
            if (x == cursor_x && y == cursor_y) { bg = XT_CUR; fg = XT_BG; }
            for (int dy = 0; dy < 8; dy++) {
                for (int dx = 0; dx < XT_CW; dx++) {
                    int px = dx;
                    int off = (dy * XT_W + px) * 4;
                    cell_img[off + 0] = (uint8_t)(bg & 0xFF);
                    cell_img[off + 1] = (uint8_t)((bg >> 8) & 0xFF);
                    cell_img[off + 2] = (uint8_t)((bg >> 16) & 0xFF);
                    cell_img[off + 3] = (uint8_t)((bg >> 24) & 0xFF);
                }
            }
            if (c != ' ' && (unsigned char)c < 128) {
                const unsigned char *g = font8x8_basic[(unsigned char)c];
                for (int dy = 0; dy < 8; dy++) {
                    for (int dx = 0; dx < 8; dx++) {
                        if (g[dy] & (1 << dx)) {
                            int off = (dy * XT_W + dx) * 4;
                            cell_img[off + 0] = (uint8_t)(fg & 0xFF);
                            cell_img[off + 1] = (uint8_t)((fg >> 8) & 0xFF);
                            cell_img[off + 2] = (uint8_t)((fg >> 16) & 0xFF);
                            cell_img[off + 3] = (uint8_t)((fg >> 24) & 0xFF);
                        }
                    }
                }
            }
            x11_put_image(window_id, x * XT_CW, y * XT_CHH, XT_CW, 8, cell_img);
        }
    }
}

static int xt_strcmp(const char *a, const char *b)
{
    while (*a && *a == *b) { a++; b++; }
    return (int)(*a) - (int)(*b);
}

