static void xt_execute(const char *cmd)
{
    if (xt_strcmp(cmd, "help") == 0) { xt_cmd_help(); return; }
    if (xt_strcmp(cmd, "clear") == 0) { xt_clear(); dirty = true; return; }
    if (xt_strcmp(cmd, "uname") == 0) { xt_puts("ArtyomX\n"); return; }
    if (xt_strcmp(cmd, "neofetch") == 0) { xt_cmd_neofetch(); return; }
    if (xt_strcmp(cmd, "exit") == 0) { sys_exit(0); }
    if (xt_strcmp(cmd, "ls") == 0) { xt_puts("bin/ dev/ tmp/\n"); return; }
    if (cmd[0]) { xt_puts("not found: "); xt_puts(cmd); xt_puts("\n"); }
}

static void xt_prompt(void) { xt_puts("$ "); }

static int x11_handshake(void)
{
    uint8_t req[12];
    req[0] = 'l'; req[1] = 0;
    x11_put16(req + 2, 11);
    x11_put16(req + 4, 0);
    x11_put16(req + 6, 0);
    x11_put16(req + 8, 0);
    x11_put16(req + 10, 0);
    if (sys_write(x11_fd, req, 12) != 12) return -1;
    uint8_t reply[4096];
    int got = 0;
    int tries = 0;
    while (got < 40 && tries < 1000) {
        int r = sys_read(x11_fd, reply + got, sizeof(reply) - got);
        if (r > 0) got += r;
        else tries++;
    }
    if (got < 40 || reply[0] != 1) return -2;
    x11_rid_base = (uint32_t)reply[32] | ((uint32_t)reply[33] << 8) | ((uint32_t)reply[34] << 16) | ((uint32_t)reply[35] << 24);
    (void)x11_rid_base;
    x11_seq = 1;
    return 0;
}

void _start(void)
{
    x11_fd = sys_socket(1, 1, 0);
    if (x11_fd < 0) sys_exit(1);
    struct { uint16_t fam; char path[108]; } addr;
    addr.fam = 1;
    const char *sp = "/tmp/.X11-unix/X0";
    int k = 0;
    while (sp[k]) { addr.path[k] = sp[k]; k++; }
    addr.path[k] = 0;
    if (sys_connect(x11_fd, &addr, 2 + k + 1) < 0) sys_exit(2);
    if (x11_handshake() < 0) sys_exit(3);

    window_id = 0x200001;
    gc_id = 0x200002;
    x11_create_window(window_id, 100, 100, XT_W, XT_H);
    x11_create_gc(gc_id, window_id);
    x11_map_window(window_id);

    pty_master = sys_open("/dev/ptmx", 2, 0);
    if (pty_master >= 0) {
        for (int i = 0; i < 8; i++) {
            char path[32];
            path[0] = '/'; path[1] = 'd'; path[2] = 'e'; path[3] = 'v';
            path[4] = '/'; path[5] = 'p'; path[6] = 't'; path[7] = 's';
            path[8] = '/'; path[9] = '0' + i; path[10] = 0;
            pty_slave = sys_open(path, 2, 0);
            if (pty_slave >= 0) break;
        }
    }

    xt_clear();
    xt_puts("ArtyomX xterm 1.0\n");
    xt_prompt();
    dirty = true;

    char buf[256];
    for (;;) {
        if (pty_slave >= 0) {
            int got = sys_read(pty_slave, buf, sizeof(buf) - 1);
            if (got > 0) {
                for (int i = 0; i < got; i++) xt_putc(buf[i]);
                dirty = true;
            }
        }
        int got = sys_read(x11_fd, buf, 32);
        if (got == 32) {
            uint8_t ev = buf[0] & 0x7F;
            if (ev == 2 || ev == 3) {
                uint8_t kc = buf[1];
                char ch = 0;
                if (kc >= 32 && kc < 127) ch = (char)kc;
                else if (kc == 8) ch = '\b';
                else if (kc == 13) ch = '\n';
                if (ch) {
                    if (ch == '\n') {
                        input_line[input_pos] = 0;
                        xt_putc('\n');
                        xt_execute(input_line);
                        input_pos = 0;
                        xt_prompt();
                    } else if (ch == '\b') {
                        if (input_pos > 0) { input_pos--; xt_putc('\b'); }
                    } else if (input_pos < 510) {
                        input_line[input_pos++] = ch;
                        xt_putc(ch);
                    }
                    dirty = true;
                }
            }
        }
        xt_render();
    }
}
